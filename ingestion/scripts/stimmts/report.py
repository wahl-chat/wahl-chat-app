"""docs/stimmts/puzzle-selection.md: every roll-call vote, and why some were picked."""

from __future__ import annotations

import re
from collections import Counter

from .votes import MIN_PARTY_UNITY, pattern

# A title that reads as a negation or a committee decision: "Ja" then means
# rejecting something, which needs a careful "Ja bedeutet …" line.
NEGATION = re.compile(
    r"^(Ablehnung|Keine?[mnrs]?\b|Beschlussempfehlung|Bisherig|Verzicht|Nicht)",
    re.I,
)
# Patterns this rare (or with an abstention) make a vote a surprise.
RARE_PATTERN = 6


def _topic(poll: dict) -> str:
    return poll["topics"][0] if poll["topics"] else "?"


def _outcome(poll: dict) -> str:
    return "angenommen" if poll["accepted"] else "abgelehnt"


def _cell(text: str, width: int) -> str:
    text = text.replace("|", "/").replace("­", "")
    return text if len(text) <= width else text[: width - 1] + "…"


def selection_report(
    polls: list[dict], picks: dict[int, str], spares: dict[int, str]
) -> str:
    patterns = Counter(pattern(poll["parties"]) for poll in polls)
    clusters = Counter(f"{poll['date']}|{_topic(poll)}" for poll in polls)

    def flags(poll: dict) -> str:
        found = []
        if any(party["unity"] < MIN_PARTY_UNITY for party in poll["parties"]):
            found.append("split")
        if NEGATION.search(poll["title"]):
            found.append("neg")
        shape = pattern(poll["parties"])
        if patterns[shape] <= RARE_PATTERN or "E" in shape:
            found.append("selten")
        same_day = clusters[f"{poll['date']}|{_topic(poll)}"]
        if same_day > 1:
            found.append(f"Cl.{same_day}")
        return ", ".join(found)

    def row(poll: dict, *extra: str) -> str:
        cells = [
            poll["date"],
            str(poll["id"]),
            _cell(poll["title"], 80),
            _cell(_topic(poll), 26),
            _outcome(poll),
            pattern(poll["parties"]),
            flags(poll),
            *extra,
        ]
        return "| " + " | ".join(cells) + " |"

    by_id = {poll["id"]: poll for poll in polls}
    chosen = [by_id[poll_id] for poll_id in picks if poll_id in by_id]
    lines = [
        f"# Stimmt's? puzzle selection: {len(polls)} roll-call votes of the "
        "21st Bundestag",
        "",
        "Generated by `ingestion/scripts/stimmts/export.py` from Abgeordnetenwatch; "
        "the reasons live in `ingestion/scripts/stimmts/selection.py`. How a "
        "chosen vote becomes a puzzle: [CONTENT.md](CONTENT.md).",
        "",
        "**Pattern**: how Linke, SPD, Grüne, CDU/CSU and AfD voted (J = Ja, "
        "N = Nein, E = Enthaltung). **Flags**: `neg`, the title reads as a "
        'negation or committee decision, so "Ja bedeutet …" needs a careful '
        "sentence; `selten`, a rare pattern or an abstention; `Cl.n`, n votes on "
        "the same day and topic; `split`, a Fraktion under 80 percent for one "
        "option, which cannot be a puzzle.",
        "",
        f"The picks in numbers: {len({_topic(p) for p in chosen})} topics, "
        f"{sum(p['date'] >= '2026-01-01' for p in chosen)} from 2026, "
        f"{sum(bool(p['accepted']) for p in chosen)} accepted and "
        f"{sum(p['accepted'] is False for p in chosen)} rejected, "
        f"{sum('E' in pattern(p['parties']) for p in chosen)} with an "
        f"abstention, {len({pattern(p['parties']) for p in chosen})} different "
        "patterns.",
        "",
        f"## The {len(chosen)} picks",
        "",
        "| Date | Poll | Title | Topic | Outcome | Pattern | Flags | Why |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for poll in sorted(chosen, key=lambda p: p["date"], reverse=True):
        lines.append(row(poll, picks[poll["id"]]))
    lines += [
        "",
        "## Spares",
        "",
        "| Date | Poll | Title | Topic | Outcome | Pattern | Flags | Note |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for poll_id, note in spares.items():
        if poll_id in by_id:
            lines.append(row(by_id[poll_id], note))
    lines += [
        "",
        "## All other votes",
        "",
        "| Date | Poll | Title | Topic | Outcome | Pattern | Flags |",
        "|---|---|---|---|---|---|---|",
    ]
    for poll in sorted(polls, key=lambda p: p["date"], reverse=True):
        if poll["id"] not in picks and poll["id"] not in spares:
            lines.append(row(poll))
    return "\n".join(lines) + "\n"
