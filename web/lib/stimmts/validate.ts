import { safeExternalUrl } from '@/lib/pledge-tracker/pledges';
import { isIsoDate } from './berlin-time';
import type {
  BillDocument,
  DocumentSubmitter,
  PartyResult,
  Puzzle,
  PuzzleOutcome,
  Schedule,
  SourceLink,
  VoteAnswer,
  VotedInDocument,
} from './types';

/**
 * A party whose members split more than this cannot be summed up in one
 * answer, so such a vote does not make a fair puzzle.
 */
const MIN_PARTY_UNITY = 0.8;

const ID_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/** A Drucksache number: Wahlperiode, slash, number ("21/6278"). */
const DRUCKSACHE_PATTERN = /^[1-9]\d*\/[1-9]\d*$/;

type Json = Record<string, unknown>;

// Puzzle files are generated by a script and edited by hand, so they are
// checked when loaded rather than trusted. A bad file fails loudly here (and
// in the tests) instead of showing a broken puzzle to players.
function fail(id: string, message: string): never {
  throw new Error(`Puzzle "${id}": ${message}`);
}

function isRecord(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function isVoteAnswer(value: string): value is VoteAnswer {
  return value === 'yes' || value === 'no' || value === 'abstain';
}

function isOutcome(value: string): value is PuzzleOutcome {
  return value === 'accepted' || value === 'rejected';
}

function readString(record: Json, key: string, id: string): string {
  const value = record[key];
  if (typeof value !== 'string' || value.trim() === '') {
    fail(id, `"${key}" must be a non-empty string`);
  }
  return value;
}

function readCount(record: Json, key: string, id: string): number {
  const value = record[key];
  if (typeof value !== 'number' || !Number.isInteger(value) || value < 0) {
    fail(id, `"${key}" must be a whole number of 0 or more`);
  }
  return value;
}

function readDate(record: Json, key: string, id: string): string {
  const value = readString(record, key, id);
  if (!isIsoDate(value)) {
    fail(id, `"${key}" must be a date like 2026-07-10`);
  }
  return value;
}

function readUrl(record: Json, key: string, what: string, id: string): string {
  const url = safeExternalUrl(readString(record, key, id));
  if (!url) {
    return fail(id, `${what} needs an http(s) url`);
  }
  return url;
}

function readLink(value: unknown, what: string, id: string): SourceLink {
  if (!isRecord(value)) {
    return fail(id, `${what} must be an object`);
  }
  return {
    label: readString(value, 'label', id),
    url: readUrl(value, 'url', what, id),
  };
}

function readDrucksache(record: Json, key: string, id: string): string {
  const value = readString(record, key, id);
  if (!DRUCKSACHE_PATTERN.test(value)) {
    fail(id, `"${key}" must be a Drucksache number like 21/6278`);
  }
  return value;
}

function readSubmitter(record: Json, id: string): DocumentSubmitter {
  const hasInitiator = record.initiator !== undefined;
  const hasFraktion = record.fraktion !== undefined;
  if (hasInitiator === hasFraktion) {
    return fail(
      id,
      'a document needs either an "initiator" or a "fraktion" with "members"',
    );
  }
  if (hasInitiator) {
    return { initiator: readString(record, 'initiator', id) };
  }
  const members = record.members;
  if (
    !Array.isArray(members) ||
    members.length === 0 ||
    !members.every((name) => typeof name === 'string' && name.trim() !== '')
  ) {
    return fail(id, '"members" must list the names of the members who signed');
  }
  return { fraktion: readString(record, 'fraktion', id), members };
}

function readVotedIn(value: unknown, id: string): VotedInDocument {
  if (!isRecord(value)) {
    return fail(id, '"votedIn" must be an object');
  }
  return {
    label: readString(value, 'label', id),
    number: readDrucksache(value, 'number', id),
    url: readUrl(value, 'url', '"votedIn"', id),
  };
}

function readDocument(value: unknown, id: string): BillDocument {
  if (!isRecord(value)) {
    return fail(id, '"document" must be an object');
  }
  return {
    ...readSubmitter(value, id),
    type: readString(value, 'type', id),
    number: readDrucksache(value, 'number', id),
    date: readDate(value, 'date', id),
    title: readString(value, 'title', id),
    url: readUrl(value, 'url', 'the document', id),
    ...(value.votedIn === undefined
      ? {}
      : { votedIn: readVotedIn(value.votedIn, id) }),
  };
}

function readParty(value: unknown, id: string): PartyResult {
  if (!isRecord(value)) {
    return fail(id, 'each party must be an object');
  }
  const partyId = readString(value, 'partyId', id);
  const answer = readString(value, 'answer', id);
  if (!isVoteAnswer(answer)) {
    return fail(id, `${partyId}: answer must be yes, no or abstain`);
  }
  const party: PartyResult = {
    partyId,
    answer,
    yes: readCount(value, 'yes', id),
    no: readCount(value, 'no', id),
    abstain: readCount(value, 'abstain', id),
    noShow: readCount(value, 'noShow', id),
  };
  const voted = party.yes + party.no + party.abstain;
  if (voted === 0) {
    return fail(id, `${partyId}: no votes were cast`);
  }
  // A share of 80% or more can only belong to the most common option, so this
  // also proves that `answer` matches the counts.
  if (party[answer] / voted < MIN_PARTY_UNITY) {
    return fail(
      id,
      `${partyId}: the counts do not support the answer "${answer}" ` +
        `(it needs at least ${MIN_PARTY_UNITY * 100}% of the votes cast)`,
    );
  }
  return party;
}

export function validatePuzzle(data: unknown): Puzzle {
  const fallbackId = isRecord(data) ? String(data.id) : '(not an object)';
  if (!isRecord(data)) {
    return fail(fallbackId, 'must be an object');
  }
  const id = readString(data, 'id', fallbackId);
  if (!ID_PATTERN.test(id)) {
    return fail(id, 'id must be lowercase words joined by hyphens');
  }

  const outcome = readString(data, 'outcome', id);
  if (!isOutcome(outcome)) {
    return fail(id, 'outcome must be accepted or rejected');
  }

  if (!Array.isArray(data.parties) || data.parties.length < 2) {
    return fail(id, 'parties must list at least two parties');
  }
  const parties = data.parties.map((party) => readParty(party, id));
  const partyIds = new Set(parties.map((party) => party.partyId));
  if (partyIds.size !== parties.length) {
    return fail(id, 'a party appears twice');
  }

  return {
    id,
    voteDate: readDate(data, 'voteDate', id),
    topic: readString(data, 'topic', id),
    title: readString(data, 'title', id),
    briefing: readString(data, 'briefing', id),
    yesMeans: readString(data, 'yesMeans', id),
    outcome,
    parties,
    unaffiliated: readCount(data, 'unaffiliated', id),
    ...(data.document === undefined
      ? {}
      : { document: readDocument(data.document, id) }),
    source: readLink(data.source, 'source', id),
  };
}

export function validateSchedule(data: unknown, puzzles: Puzzle[]): Schedule {
  const id = 'schedule';
  if (!isRecord(data)) {
    return fail(id, 'must be an object');
  }
  if (!Array.isArray(data.puzzleIds) || data.puzzleIds.length === 0) {
    return fail(id, 'puzzleIds must list at least one puzzle');
  }
  const known = new Set(puzzles.map((puzzle) => puzzle.id));
  const seen = new Set<string>();
  const puzzleIds = data.puzzleIds.map((entry) => {
    if (typeof entry !== 'string' || !known.has(entry)) {
      return fail(id, `unknown puzzle id ${JSON.stringify(entry)}`);
    }
    if (seen.has(entry)) {
      return fail(id, `puzzle "${entry}" is scheduled twice`);
    }
    seen.add(entry);
    return entry;
  });
  return { startDate: readDate(data, 'startDate', id), puzzleIds };
}
