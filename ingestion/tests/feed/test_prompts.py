import hashlib

from ingestion.feed.prompts import (
    _ATTRIBUTION_RULE,
    _GROUNDING_RULE,
    _NEUTRALITY_RULE,
    _POSITION_FIDELITY_RULE,
    _POSITION_SENTENCE_RULE,
    DebateDraft,
    PartyPositionDraft,
    PositionCheck,
    VoteEnrichment,
    format_debate_prompt,
    format_positions_prompt,
    format_translation_prompt,
    format_verify_prompt,
    format_vote_prompt,
)


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def test_generation_prompts_change_only_on_purpose() -> None:
    # A change here is a prompt change: bump PROMPT_VERSION, run the eval, and
    # rebuild on purpose (--force). Stored items are not regenerated by it.
    assert (
        _sha(format_vote_prompt("Bundestag", "[V1] Antrag"))
        == "0cd5786df7b9272ee9a04e9e21608da503582d43c4a4cdb95f4a521af9b65310"
    )
    assert (
        _sha(
            format_debate_prompt(
                "Bundestag",
                "24.09.2026",
                "Wohnungsbau",
                "spd, cdu",
                "- [R1] Anna (spd): Wohnungen",
            )
        )
        == "f7eefaad1606bb7a27cc5f375b8ed736b9d01035ff50d46c842c7c24c24e604e"
    )
    assert (
        _sha(
            format_positions_prompt(
                "Bundestag", "Wohnungsbau", "cdu", "- [R1] Bernd (cdu): Kosten"
            )
        )
        == "54d974da88571a6aa2588674e86c40adcbc1bfe5a600a28d757bae9ab72825ce"
    )
    assert (
        _sha(
            format_verify_prompt(
                "Bundestag", "Wohnungsbau", "[P1] spd: Fordern mehr.", "## spd"
            )
        )
        == "6f06f603c48a84c540351e8bae8e2c874237f5038a8e5ca75ae85453b58f0909"
    )


def test_every_position_prompt_holds_the_same_editorial_rules() -> None:
    for prompt in (
        format_debate_prompt("Bundestag", "", "", "", ""),
        format_positions_prompt("Bundestag", "", "", ""),
    ):
        for rule in (
            _NEUTRALITY_RULE,
            _GROUNDING_RULE,
            _ATTRIBUTION_RULE,
            _POSITION_FIDELITY_RULE,
        ):
            assert rule in prompt


def test_the_schema_carries_the_rules_for_each_field() -> None:
    position = PartyPositionDraft.model_fields["position"].description or ""
    assert _POSITION_SENTENCE_RULE in position
    debate = DebateDraft.model_json_schema()["properties"]
    assert "Genau 3" in debate["key_points"]["description"]
    assert "positions" in debate["summary"]["description"]
    # The prompts no longer repeat them.
    prompt = format_debate_prompt("Bundestag", "", "", "", "")
    assert _POSITION_SENTENCE_RULE not in prompt
    assert "key_points" not in prompt


def test_the_check_gives_its_reason_before_its_verdict() -> None:
    assert list(PositionCheck.model_fields) == ["ref", "reason", "supported"]


def test_translation_is_held_to_the_same_editorial_rules() -> None:
    prompt = format_translation_prompt("Bundestag", "[I1]\nheadline: Test")
    for rule in (
        _NEUTRALITY_RULE,
        _GROUNDING_RULE,
        _ATTRIBUTION_RULE,
        _POSITION_SENTENCE_RULE,
    ):
        assert rule in prompt
    assert "neutrale Übersicht" in prompt
    assert prompt.endswith("[I1]\nheadline: Test\n")


def test_votes_and_debates_are_tagged_alike() -> None:
    vote = VoteEnrichment.model_fields["topics"].description
    debate = DebateDraft.model_fields["topics"].description
    assert vote == debate
    assert vote is not None
    assert "'other' nur, wenn nichts passt" in vote
    # The model answers with the key in front of each "- key: label" line.
    assert "Kennung aus der Themenliste" in vote
    assert "Themenliste:" in format_vote_prompt("Bundestag", "")
    assert "Themenliste:" in format_debate_prompt("Bundestag", "", "", "", "")
