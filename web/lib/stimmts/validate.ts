import { safeExternalUrl } from '@/lib/pledge-tracker/pledges';
import { isIsoDate } from './berlin-time';
import { SEATING_ORDER } from './parties';
import { feedTopicFor } from './topic';
import type {
  BillDocument,
  DocumentSubmitter,
  KeyPoint,
  KeyPointSource,
  PartyResult,
  Puzzle,
  PuzzleOutcome,
  SourceLink,
  VoteAnswer,
  VotedInDocument,
} from './types';

/**
 * A party whose members split more than this cannot be summed up in one
 * answer, so such a vote does not make a fair puzzle.
 */
const MIN_PARTY_UNITY = 0.8;

/** Key points are read at a glance on a phone, before the guess. */
const KEY_POINT_COUNT = 3;
const MAX_KEY_POINT_WORDS = 12;

/** It must fit the feed card's "Heute: …" line on a phone. */
const MAX_SHORT_NAME_LENGTH = 22;

/** The article lets the name read as a noun after "Heute: ". */
const SHORT_NAME_PATTERN = /^(Der|Die|Das) \S/;

const ID_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/** A Drucksache number: Wahlperiode, slash, number ("21/6278"). */
const DRUCKSACHE_PATTERN = /^[1-9]\d*\/[1-9]\d*$/;

/** Two-digit Wahlperiode and at most five digits, as the PDF URL expects. */
const KEY_POINT_DOCUMENT_PATTERN = /^\d{2}\/\d{1,5}$/;

type Json = Record<string, unknown>;

// Puzzle files are generated by a script and edited by hand, so they are
// checked when loaded rather than trusted. A bad file fails loudly here (and
// in the tests) instead of showing a broken puzzle to players.
function fail(id: string, message: string): never {
  throw new Error(`Puzzle "${id}": ${message}`);
}

function isRecord(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function isVoteAnswer(value: string): value is VoteAnswer {
  return value === 'yes' || value === 'no' || value === 'abstain';
}

function isOutcome(value: string): value is PuzzleOutcome {
  return value === 'accepted' || value === 'rejected';
}

function readString(record: Json, key: string, id: string): string {
  const value = record[key];
  if (typeof value !== 'string' || value.trim() === '') {
    fail(id, `"${key}" must be a non-empty string`);
  }
  return value;
}

function readCount(record: Json, key: string, id: string): number {
  const value = record[key];
  if (typeof value !== 'number' || !Number.isInteger(value) || value < 0) {
    fail(id, `"${key}" must be a whole number of 0 or more`);
  }
  return value;
}

function readDate(record: Json, key: string, id: string): string {
  const value = readString(record, key, id);
  if (!isIsoDate(value)) {
    fail(id, `"${key}" must be a date like 2026-07-10`);
  }
  return value;
}

function readUrl(record: Json, key: string, what: string, id: string): string {
  const url = safeExternalUrl(readString(record, key, id));
  if (!url) {
    return fail(id, `${what} needs an http(s) url`);
  }
  return url;
}

function readLink(value: unknown, what: string, id: string): SourceLink {
  if (!isRecord(value)) {
    return fail(id, `${what} must be an object`);
  }
  return {
    label: readString(value, 'label', id),
    url: readUrl(value, 'url', what, id),
  };
}

function readDrucksache(record: Json, key: string, id: string): string {
  const value = readString(record, key, id);
  if (!DRUCKSACHE_PATTERN.test(value)) {
    fail(id, `"${key}" must be a Drucksache number like 21/6278`);
  }
  return value;
}

function readSubmitter(record: Json, id: string): DocumentSubmitter {
  const hasInitiator = record.initiator !== undefined;
  const hasFraktion = record.fraktion !== undefined;
  if (hasInitiator === hasFraktion) {
    return fail(
      id,
      'a document needs either an "initiator" or a "fraktion" with "members"',
    );
  }
  if (hasInitiator) {
    return { initiator: readString(record, 'initiator', id) };
  }
  const members = record.members;
  if (
    !Array.isArray(members) ||
    members.length === 0 ||
    !members.every((name) => typeof name === 'string' && name.trim() !== '')
  ) {
    return fail(id, '"members" must list the names of the members who signed');
  }
  const submitter = { fraktion: readString(record, 'fraktion', id), members };
  if (record.memberCount === undefined) {
    return submitter;
  }
  const memberCount = readCount(record, 'memberCount', id);
  if (memberCount < members.length) {
    return fail(id, '"memberCount" cannot be less than the members named');
  }
  return { ...submitter, memberCount };
}

function readVotedIn(value: unknown, id: string): VotedInDocument {
  if (!isRecord(value)) {
    return fail(id, '"votedIn" must be an object');
  }
  return {
    label: readString(value, 'label', id),
    number: readDrucksache(value, 'number', id),
    url: readUrl(value, 'url', '"votedIn"', id),
  };
}

function readDocument(value: unknown, id: string): BillDocument {
  if (!isRecord(value)) {
    return fail(id, '"document" must be an object');
  }
  return {
    ...readSubmitter(value, id),
    type: readString(value, 'type', id),
    number: readDrucksache(value, 'number', id),
    date: readDate(value, 'date', id),
    title: readString(value, 'title', id),
    url: readUrl(value, 'url', 'the document', id),
    ...(value.votedIn === undefined
      ? {}
      : { votedIn: readVotedIn(value.votedIn, id) }),
  };
}

function readTopic(record: Json, id: string): string {
  const topic = readString(record, 'topic', id);
  if (feedTopicFor(topic) === undefined) {
    return fail(
      id,
      `topic "${topic}" has no feed topic; add it to topic.ts so it gets its dot`,
    );
  }
  return topic;
}

function countWords(text: string): number {
  return text.split(/\s+/).filter(Boolean).length;
}

function readPage(record: Json, where: string, id: string): number {
  const page = record.page;
  if (typeof page !== 'number' || !Number.isInteger(page) || page < 1) {
    return fail(id, `${where} "page" must be a whole number of 1 or more`);
  }
  return page;
}

function readKeyPointSource(
  value: unknown,
  where: string,
  id: string,
): KeyPointSource {
  if (!isRecord(value)) {
    return fail(id, `${where} needs a "source" object with document and page`);
  }
  const document = readString(value, 'document', id);
  if (!KEY_POINT_DOCUMENT_PATTERN.test(document)) {
    fail(id, `${where} "document" must be a Drucksache number like 21/8157`);
  }
  return {
    document,
    page: readPage(value, where, id),
  };
}

function readKeyPointText(value: unknown, where: string, id: string): string {
  if (typeof value !== 'string' || value.trim() === '') {
    return fail(id, `${where} "text" must be a non-empty string`);
  }
  if (value !== value.trim()) {
    return fail(id, `${where} has leading or trailing whitespace`);
  }
  // Nothing renders emphasis, so a stray marker would show up as literal
  // asterisks on the card.
  if (value.includes('*')) {
    return fail(id, `${where} must not contain "*"; key points have no markup`);
  }
  if (countWords(value) > MAX_KEY_POINT_WORDS) {
    return fail(id, `${where} is longer than ${MAX_KEY_POINT_WORDS} words`);
  }
  return value;
}

function readKeyPoint(value: unknown, index: number, id: string): KeyPoint {
  const where = `key point ${index + 1}`;
  if (!isRecord(value)) {
    return fail(id, `${where} must be an object with "text" and "source"`);
  }
  return {
    text: readKeyPointText(value.text, where, id),
    source: readKeyPointSource(value.source, where, id),
  };
}

function readKeyPoints(
  value: unknown,
  id: string,
): [KeyPoint, KeyPoint, KeyPoint] {
  if (!Array.isArray(value) || value.length !== KEY_POINT_COUNT) {
    return fail(id, `"keyPoints" must list exactly ${KEY_POINT_COUNT} points`);
  }
  const [first, second, third] = value.map((point, index) =>
    readKeyPoint(point, index, id),
  );
  return [first, second, third];
}

/**
 * A key point may only cite the bill itself or the version voted on: those
 * are the PDFs the puzzle links to, so a reader can check what they are
 * shown against the same documents.
 */
function checkKeyPointDocuments(
  keyPoints: KeyPoint[],
  document: BillDocument | undefined,
  id: string,
): void {
  if (!document) {
    return;
  }
  const allowed = [document.number];
  if (document.votedIn) {
    allowed.push(document.votedIn.number);
  }
  keyPoints.forEach((point, index) => {
    if (!allowed.includes(point.source.document)) {
      fail(
        id,
        `key point ${index + 1} cites ${point.source.document}, ` +
          `but the puzzle's documents are ${allowed.join(' and ')}`,
      );
    }
  });
}

function readShortName(record: Json, id: string): string {
  const name = readString(record, 'shortName', id);
  if (name.length > MAX_SHORT_NAME_LENGTH) {
    fail(id, `"shortName" is longer than ${MAX_SHORT_NAME_LENGTH} characters`);
  }
  if (!SHORT_NAME_PATTERN.test(name)) {
    fail(id, '"shortName" must start with Der, Die or Das');
  }
  return name;
}

function readParty(value: unknown, id: string): PartyResult {
  if (!isRecord(value)) {
    return fail(id, 'each party must be an object');
  }
  const partyId = readString(value, 'partyId', id);
  const answer = readString(value, 'answer', id);
  if (!isVoteAnswer(answer)) {
    return fail(id, `${partyId}: answer must be yes, no or abstain`);
  }
  const party: PartyResult = {
    partyId,
    answer,
    yes: readCount(value, 'yes', id),
    no: readCount(value, 'no', id),
    abstain: readCount(value, 'abstain', id),
    noShow: readCount(value, 'noShow', id),
  };
  const voted = party.yes + party.no + party.abstain;
  if (voted === 0) {
    return fail(id, `${partyId}: no votes were cast`);
  }
  // A share of 80% or more can only belong to the most common option, so this
  // also proves that `answer` matches the counts.
  if (party[answer] / voted < MIN_PARTY_UNITY) {
    return fail(
      id,
      `${partyId}: the counts do not support the answer "${answer}" ` +
        `(it needs at least ${MIN_PARTY_UNITY * 100}% of the votes cast)`,
    );
  }
  return party;
}

export function validatePuzzle(data: unknown): Puzzle {
  const fallbackId = isRecord(data) ? String(data.id) : '(not an object)';
  if (!isRecord(data)) {
    return fail(fallbackId, 'must be an object');
  }
  const id = readString(data, 'id', fallbackId);
  if (!ID_PATTERN.test(id)) {
    return fail(id, 'id must be lowercase words joined by hyphens');
  }

  const outcome = readString(data, 'outcome', id);
  if (!isOutcome(outcome)) {
    return fail(id, 'outcome must be accepted or rejected');
  }

  if (!Array.isArray(data.parties)) {
    return fail(id, 'parties must be a list');
  }
  const parties = data.parties.map((party) => readParty(party, id));
  if (parties.map((party) => party.partyId).join() !== SEATING_ORDER.join()) {
    return fail(
      id,
      `parties must be ${SEATING_ORDER.join(', ')}, in that order (left to right in the chamber)`,
    );
  }

  const keyPoints =
    data.keyPoints === undefined
      ? undefined
      : readKeyPoints(data.keyPoints, id);
  const document =
    data.document === undefined ? undefined : readDocument(data.document, id);
  if (keyPoints) {
    checkKeyPointDocuments(keyPoints, document, id);
  }

  return {
    id,
    voteDate: readDate(data, 'voteDate', id),
    topic: readTopic(data, id),
    title: readString(data, 'title', id),
    shortName: readShortName(data, id),
    briefing: readString(data, 'briefing', id),
    ...(keyPoints ? { keyPoints } : {}),
    yesMeans: readString(data, 'yesMeans', id),
    outcome,
    parties,
    unaffiliated: readCount(data, 'unaffiliated', id),
    ...(document ? { document } : {}),
    source: readLink(data.source, 'source', id),
  };
}

export function validatePuzzleOrder(
  data: unknown,
  puzzles: Puzzle[],
): string[] {
  const id = 'schedule';
  if (!isRecord(data)) {
    return fail(id, 'must be an object');
  }
  if (!Array.isArray(data.puzzleIds) || data.puzzleIds.length === 0) {
    return fail(id, 'puzzleIds must list at least one puzzle');
  }
  const known = new Set(puzzles.map((puzzle) => puzzle.id));
  const seen = new Set<string>();
  const puzzleIds = data.puzzleIds.map((entry) => {
    if (typeof entry !== 'string' || !known.has(entry)) {
      return fail(id, `unknown puzzle id ${JSON.stringify(entry)}`);
    }
    if (seen.has(entry)) {
      return fail(id, `puzzle "${entry}" is scheduled twice`);
    }
    seen.add(entry);
    return entry;
  });
  return puzzleIds;
}
